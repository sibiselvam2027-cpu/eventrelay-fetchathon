"""Persist invocation-local SQLite state through Agentverse ctx.storage.

Agentverse can recreate module globals for every message. The coordinator must
open a session, perform its synchronous transition, checkpoint BEFORE awaiting
an outbound message, and close the session. Both databases share one storage
assignment. This assumes one sequential coordinator writer; ctx.storage does
not provide a distributed compare-and-swap transaction here. Unchanged sessions
do not write, and a changed session rejects a visibly newer stored snapshot.
This detects stale snapshots only when storage.get exposes the latest value.

The SQL snapshots are generated by sqlite3.iterdump from this application's own
databases. They are trusted application storage, never user-supplied commands.
No database or other runtime state is written to the filesystem.
"""

from __future__ import annotations

from contextlib import contextmanager
import json
import sqlite3
import threading
import time

from .router import ConversationService
from .store import EventStore


STORAGE_KEY = "eventrelay.snapshot.v1"
SCHEMA_VERSION = 1


class HostedStateError(Exception):
    def __init__(self, code: str, message: str):
        self.code = code
        self.message = message
        super().__init__(message)


def _restore(connection: sqlite3.Connection, sql: str) -> None:
    """Restore only a previously generated, trusted in-memory SQLite dump."""
    connection.execute("PRAGMA foreign_keys=OFF")
    names = [row[0] for row in connection.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")]
    try:
        for name in names:
            # Names originate from our schema; quote them defensively anyway.
            connection.execute('DROP TABLE "' + name.replace('"', '""') + '"')
        connection.executescript(sql)
    except sqlite3.Error:
        if connection.in_transaction:
            connection.rollback()
        raise HostedStateError("invalid_snapshot", "Stored EventRelay state could not be restored.") from None
    finally:
        connection.execute("PRAGMA foreign_keys=ON")


class _MemoryConversationService(ConversationService):
    """Reuse conversation behavior without invoking its filesystem constructor."""

    def __init__(self, store: EventStore, sql: str | None = None):
        self.store = store
        self.path = ":memory:"
        self._held = sqlite3.connect(":memory:", isolation_level=None, check_same_thread=False)
        self._held.row_factory = sqlite3.Row
        self._lock = threading.RLock()
        self._held.execute("CREATE TABLE conversations(actor TEXT PRIMARY KEY,state TEXT NOT NULL)")
        if sql is not None:
            _restore(self._held, sql)

    @contextmanager
    def _db(self):
        with self._lock:
            try:
                self._held.execute("BEGIN IMMEDIATE")
                yield self._held
                self._held.commit()
            except Exception:
                if self._held.in_transaction:
                    self._held.rollback()
                raise


class HostedSession:
    def __init__(self, storage, store: EventStore, service: _MemoryConversationService, baseline):
        self.storage = storage
        self.store = store
        self.service = service
        self._closed = False
        self._stored_baseline = json.loads(json.dumps(baseline)) if baseline is not None else None
        self._generated_baseline = self._dump() if baseline is not None else None

    def _dump(self):
        return {
            "schema_version": SCHEMA_VERSION,
            "event_sql": "\n".join(self.store._anchor.iterdump()),
            "conversation_sql": "\n".join(self.service._held.iterdump()),
        }

    def checkpoint(self) -> dict:
        if self._closed:
            raise HostedStateError("session_closed", "This hosted invocation has already closed.")
        # No await is permitted between the state transition and this single
        # assignment. This is not a cross-worker CAS or a delivery transaction.
        snapshot = self._dump()
        encoded = json.dumps(snapshot, sort_keys=True, separators=(",", ":"))
        result = {"schema_version": SCHEMA_VERSION, "storage_key": STORAGE_KEY,
                  "snapshot_bytes": len(encoded.encode("utf-8")), "written": False}
        if snapshot == self._generated_baseline:
            return result
        if _snapshot(self.storage) != self._stored_baseline:
            raise HostedStateError("stale_snapshot", "Stored EventRelay state changed while handling this request. Refresh status and retry.")
        self.storage.set(STORAGE_KEY, encoded)
        self._stored_baseline = snapshot
        self._generated_baseline = snapshot
        result["written"] = True
        return result

    def close(self) -> None:
        if not self._closed:
            self.service._held.close()
            self.store._anchor.close()
            self._closed = True

    def __enter__(self):
        if self._closed:
            raise HostedStateError("session_closed", "This hosted invocation has already closed.")
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        try:
            if exc_type is None:
                self.checkpoint()
        finally:
            self.close()
        return False


def _snapshot(storage) -> dict | None:
    value = storage.get(STORAGE_KEY)
    if value is None:
        return None
    try:
        snapshot = json.loads(value) if isinstance(value, str) else value
    except (ValueError, TypeError):
        raise HostedStateError("invalid_snapshot", "Stored EventRelay state is not valid JSON.") from None
    if (not isinstance(snapshot, dict) or type(snapshot.get("schema_version")) is not int
            or snapshot["schema_version"] != SCHEMA_VERSION
            or not isinstance(snapshot.get("event_sql"), str)
            or not isinstance(snapshot.get("conversation_sql"), str)):
        raise HostedStateError("invalid_snapshot", "Stored EventRelay state has an unsupported schema.")
    return snapshot


def open_hosted_service(storage, now=time.time) -> HostedSession:
    """Create one invocation's coordinator state using only storage.get/set."""
    snapshot = _snapshot(storage)
    store = EventStore(":memory:", now=now)
    service = None
    try:
        if snapshot is not None:
            _restore(store._anchor, snapshot["event_sql"])
        store.seed_demo()
        service = _MemoryConversationService(store, snapshot["conversation_sql"] if snapshot else None)
        return HostedSession(storage, store, service, snapshot)
    except Exception:
        if service is not None:
            service._held.close()
        store._anchor.close()
        raise
